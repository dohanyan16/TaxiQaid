// Deterministic operational-data deployment packaging. Never reads Secrets or deploys.
const fs=require('node:fs'),crypto=require('node:crypto'),check=process.argv.includes('--check');
const paths=[
 'shared/permission-catalog.js','shared/permission-model.js','shared/auth-contract.js','shared/sheets-model.js',
 'supabase/functions/operational-data/google.mjs',
 'supabase/functions/operational-data/google-write.mjs',
 'supabase/functions/operational-data/write-engine.mjs',
 'supabase/functions/operational-data/write-receipts.mjs',
 'supabase/functions/operational-data/handler.mjs',
 'supabase/functions/operational-data/index.ts'
];
const source=Object.fromEntries(paths.map(p=>[p,fs.readFileSync(p,'utf8')]));
const hash=crypto.createHash('sha256').update(JSON.stringify(source)).digest('hex');
function shared(p){return source[p].replace(/\nif\(typeof module[^\n]+/g,'').replace("typeof TaxiQaidPermissionCatalog!=='undefined'?TaxiQaidPermissionCatalog:require('./permission-catalog.js')",'TaxiQaidPermissionCatalog').replace("typeof libphonenumber!=='undefined'?libphonenumber:require('../assets/vendor/phone/libphonenumber-max.js')",'libphonenumber');}
const strip=p=>source[p].replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
const google=strip(paths[4]),writerGoogle=strip(paths[5]),engine=strip(paths[6]),receipts=strip(paths[7]);
const handler=strip(paths[8]).replace(/^const require=.*;$/m,'const contract=TaxiQaidAuthContract,permissions=TaxiQaidPermissionModel,schema=TaxiQaidSheetsModel;');
const entry=strip(paths[9]).replace('(name:string)','(name)').replaceAll('(token:string)','(token)').replace('(result:Record<string,unknown>)','(result)');
const artifact='// GENERATED by scripts/build-operational-data.cjs; source SHA-256 '+hash+'\n'
 +"import {createClient} from 'npm:@supabase/supabase-js@2.119.0';\n"
 +"import {parsePhoneNumberFromString} from 'npm:libphonenumber-js@1.12.27';\n"
 +"const libphonenumber={parsePhoneNumberFromString};\n"
 +paths.slice(0,4).map(shared).join('\n')+'\n'
 +google+'\n'+writerGoogle+'\n'+engine+'\n'+receipts+'\n'+handler+'\n'+entry;
const target='supabase/dashboard/operational-data.mjs';
if(check){if(fs.readFileSync(target,'utf8')!==artifact)throw new Error('Operational-data deployment artifact drift');}
else fs.writeFileSync(target,artifact);
console.log('PASS: staged operational-data artifact '+hash);
